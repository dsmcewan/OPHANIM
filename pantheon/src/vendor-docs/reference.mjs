// The labs side by side: for each capability, the page of each lab's own documentation that describes it.
//
// The labs do not offer the same methods under other names. One calls a "response", one an "interaction", one a "message";
// reasoning is an effort level here and a thinking level there; one counts tokens with a method and one has none. Which page
// answers a topic is chosen by a person (config/vendor-topics.json). Everything else is the lab's: the title, the
// description and the digest of each page are read from the capture, so the reference cannot say more than the lab's index
// does, and a chosen page that is gone, or that changed since it was read, is reported for a person to read again.
import { ENDED } from "./check.mjs";

export const SCHEMA = "pantheon.vendor-reference/v1";
const fail = (code, message) => Object.assign(new Error(message), { code });
const day = t => String(t).slice(0, 10);

/** → {schema, labs: {lab: {read, pages: {listed, captured}, indexes, sections, topics: {id: [{url, title, description, sha256}]}}}, problems} */
export function reference({ topics, manifests }) {
  const labs = {}, problems = [];
  for (const [lab, chosen] of Object.entries(topics.pages)) {
    const m = manifests[lab];
    if (!m) throw fail("VENDOR_NOT_CAPTURED", `${lab}: no capture of this lab's documentation to read the reference from`);
    const byUrl = new Map(m.pages.map(p => [p.url, p]));
    const counts = new Map();
    for (const p of m.pages) { const s = p.section ?? "(no section)"; counts.set(s, (counts.get(s) ?? 0) + 1); }
    const of = {};
    for (const { id } of topics.topics) {
      of[id] = [];
      for (const url of chosen[id] ?? []) {
        const p = byUrl.get(url);
        if (p?.status === "captured") of[id].push({ url, title: p.title ?? null, description: p.description ?? null, sha256: p.sha256 });
        else problems.push({ lab, topic: id, url, why: p ? `listed by the lab and not captured (${p.why ?? p.status})` : "not in the lab's documentation as captured" });
      }
    }
    labs[lab] = { read: m.read, pages: { listed: m.pages.length, captured: m.pages.filter(p => p.status === "captured").length },
      indexes: (m.indexes ?? []).filter(i => i.status === "captured").map(i => ({ url: i.url, sha256: i.sha256 })),
      sections: [...counts].map(([section, pages]) => ({ section, pages })).sort((a, b) => b.pages - a.pages || (a.section < b.section ? -1 : 1)),
      topics: of };
  }
  return { schema: SCHEMA, labs, problems };
}

/** The topic pages whose bytes differ from the kept reference's: [{lab, topic, url, why}]. A page newly chosen is not one. */
export function referenceChanges(kept, fresh) {
  const out = [];
  for (const [lab, l] of Object.entries(fresh.labs)) for (const [topic, pages] of Object.entries(l.topics)) for (const p of pages) {
    const was = kept?.labs?.[lab]?.topics?.[topic]?.find(k => k.url === p.url);
    if (was && was.sha256 !== p.sha256) out.push({ lab, topic, url: p.url, why: `changed since it was read ${day(kept.labs[lab].read)}` });
  }
  return out;
}

/** The captured pages of one lab that hold every word, in the title, description, section or address. */
export function find({ manifest, words }) {
  const wanted = words.map(w => String(w).toLowerCase()).filter(Boolean);
  if (!wanted.length) return [];
  return manifest.pages.filter(p => p.status === "captured" && wanted.every(w => `${p.title ?? ""} ${p.description ?? ""} ${p.section ?? ""} ${p.url}`.toLowerCase().includes(w)));
}

const cell = s => String(s ?? "").replace(/\s*\r?\n\s*/g, " ").replace(/\|/g, "\\|").trim();
const n = v => (typeof v === "number" ? v.toLocaleString("en-US") : "");

/** The written page (docs/vendor-labs.md). The same inputs give the same text. */
export function render({ reference: ref, topics, catalogues, registry = {} }) {
  const labs = Object.keys(ref.labs);
  const out = ["# The labs' own documentation: methods, functionality and models", "",
    "Generated by `node pantheon/bin/pantheon-vendor-docs.mjs reference --write`. Do not edit it by hand: a test holds it to the data it is generated from (`pantheon/src/config/vendor-reference.json`, `vendor-catalog/`, `vendor-topics.json`).", "",
    "Every title, description and figure below is the lab's own, read from its documentation on the day shown. Which page answers a topic was chosen by a person. The pages themselves are not in the repository: `pantheon-vendor-docs capture` reads them again (about a minute), `find <lab> <words>` searches them and `show <lab> <address>` prints one. How a new model is taken up is in `docs/model-updates.md`.", "",
    "## What each lab's documentation holds", "", "| Lab | Read | Pages listed | Captured | Largest sections |", "|---|---|---|---|---|"];
  for (const lab of labs) {
    const l = ref.labs[lab], shown = l.sections.slice(0, 8);
    out.push(`| ${lab} | ${day(l.read)} | ${l.pages.listed} | ${l.pages.captured} | ${cell(shown.map(s => `${s.section} (${s.pages})`).join(", ") + (l.sections.length > shown.length ? `, and ${l.sections.length - shown.length} more` : ""))} |`);
  }
  out.push("", "## Where each lab documents each capability");
  for (const t of topics.topics) {
    out.push("", `### ${t.title}`, "", t.what, "", "| Lab | Page | The lab's description |", "|---|---|---|");
    for (const lab of labs) {
      const pages = ref.labs[lab].topics[t.id] ?? [];
      if (!pages.length) out.push(`| ${lab} | no page of this lab's index was found for this topic |  |`);
      for (const p of pages) out.push(`| ${lab} | [${cell(p.title ?? p.url)}](${p.url}) | ${cell(p.description)} |`);
    }
  }
  out.push("", "## Models each lab describes", "",
    "Every model here is catalogued; only the ones marked are registered for use in this repository (`pantheon/src/config/models.json`). A blank cell means the model's page does not state it.");
  for (const lab of labs) {
    const models = Object.entries(catalogues[lab]?.models ?? {}).sort(([a], [b]) => (a < b ? -1 : 1));
    const gone = models.filter(([, m]) => m.gone_since), described = models.filter(([, m]) => !m.gone_since);
    const ended = described.filter(([, m]) => m.status && ENDED.test(`${m.status.value} ${m.status.quote ?? ""}`));
    const current = described.filter(e => !ended.includes(e));
    const registered = new Set(Object.values(registry[lab] ?? {}));
    out.push("", `### ${lab}: ${current.length} described and current, ${ended.length} the lab calls ended, ${gone.length} no longer described`);
    if (!current.length) continue;
    out.push("", "| Model | Context window | Max output | Reasoning levels | Status | Registered here |", "|---|---|---|---|---|---|");
    for (const [id, m] of current) {
      const f = m.facts ?? {}, levels = f.efforts?.values?.join(", ") ?? "";
      const preset = f.effort_default?.value ? `${levels ? " " : ""}(default ${f.effort_default.value})` : "";
      out.push(`| \`${id}\` | ${n(f.context_window?.value)} | ${n(f.max_output?.value)} | ${cell(levels + preset)} | ${cell(m.status?.value)} | ${registered.has(id) || (m.aliases ?? []).some(a => registered.has(a)) ? "yes" : ""} |`);
    }
  }
  return out.join("\n") + "\n";
}
